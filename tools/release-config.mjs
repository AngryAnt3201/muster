// Spreads app.config.json (the one place for the app's name, version and ids) to everything that needs it:
//   ios/app.xcconfig             display name, version, build, bundle id, team (Xcode reads it for Debug and Release)
//   ios/App/ExportOptions.plist  App Store export with automatic signing for the team
//   store/metadata.json          synced fields, then store/LISTING.md is regenerated from it
//   site/*.html, store/RELEASE-CHECKLIST.md   the old store name, email and site URL are replaced with the new ones
// Also checks App Store length limits. Run: npm run release:config (ios:release and ios:release:dry run it too).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => {
  const full = join(root, p);
  if (existsSync(full) && readFileSync(full, "utf8") === s) return;
  writeFileSync(full, s);
  console.log("  wrote", p);
};

const app = JSON.parse(read("app.config.json"));
const problems = [];
const need = (ok, msg) => { if (!ok) problems.push(msg); };
need(app.storeName && app.storeName.length <= 30, `storeName must be 1-30 characters (is ${app.storeName?.length})`);
need(app.displayName && app.displayName.length <= 30, "displayName missing or too long");
need(/^\d+\.\d+\.\d+$/.test(app.version), `version must look like 1.0.0 (is ${app.version})`);
need(Number.isInteger(app.build) && app.build > 0, "build must be a positive integer");
need(/^[A-Z0-9]{10}$/.test(app.teamId), "teamId must be a 10-character Apple team id");
need(/^[a-z0-9.-]+$/i.test(app.bundleId), "bundleId looks wrong");
need(/^https:\/\/[^/]+/.test(app.siteUrl), "siteUrl must be an https URL");
if (app.displayName.length > 12) console.warn(`  note: displayName "${app.displayName}" is over 12 characters; iOS truncates it under the icon`);

// ---------------------------------------------------------------- Xcode
const xc = (v) => String(v).replace(/\$/g, "$$$$");
write("ios/app.xcconfig", [
  "// Generated by tools/release-config.mjs from app.config.json. Edit app.config.json, then run: npm run release:config",
  `APP_DISPLAY_NAME = ${xc(app.displayName)}`,
  `MARKETING_VERSION = ${app.version}`,
  `CURRENT_PROJECT_VERSION = ${app.build}`,
  `PRODUCT_BUNDLE_IDENTIFIER = ${app.bundleId}`,
  `DEVELOPMENT_TEAM = ${app.teamId}`,
  "",
].join("\n"));

write("ios/App/ExportOptions.plist", `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by tools/release-config.mjs from app.config.json. Used by: npm run ios:export -->
<plist version="1.0">
<dict>
	<key>method</key>
	<string>app-store-connect</string>
	<key>destination</key>
	<string>export</string>
	<key>teamID</key>
	<string>${app.teamId}</string>
	<key>signingStyle</key>
	<string>automatic</string>
	<key>uploadSymbols</key>
	<true/>
	<key>stripSwiftSymbols</key>
	<true/>
	<key>manageAppVersionAndBuildNumber</key>
	<false/>
</dict>
</plist>
`);

// ---------------------------------------------------------------- store listing
const metaPath = "store/metadata.json";
const meta = JSON.parse(read(metaPath));
const old = { name: meta.name, email: meta.reviewContact?.email, site: meta.marketingUrl, copyright: meta.copyright };
const site = app.siteUrl.replace(/\/$/, "");
Object.assign(meta, {
  name: app.storeName,
  bundleId: app.bundleId,
  sku: app.bundleId,
  version: app.version,
  copyright: app.copyright,
  supportUrl: `${site}/support.html`,
  privacyPolicyUrl: `${site}/privacy.html`,
  marketingUrl: site,
});
meta.reviewContact = { ...meta.reviewContact, email: app.supportEmail };
if (meta.nameOptions) meta.nameOptions.chosen = app.storeName;
write(metaPath, JSON.stringify(meta, null, 2) + "\n");

const fill = (s) => (s ?? "").replaceAll("{{name}}", app.storeName);
const fields = {
  name: [meta.name, 30],
  subtitle: [meta.subtitle, 30],
  promotionalText: [meta.promotionalText, 170],
  description: [fill(meta.description), 4000],
  keywords: [meta.keywords, 100],
  reviewNotes: [fill(meta.reviewNotes), 4000],
};
for (const [k, [v, max]] of Object.entries(fields)) need(v && [...v].length <= max, `${k} is ${[...(v ?? "")].length} characters (max ${max})`);
need(!/,\s/.test(meta.keywords), "keywords: no spaces after commas (they waste characters)");
const nameWords = new Set(`${meta.name} ${meta.subtitle}`.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean));
const dupes = meta.keywords.toLowerCase().split(",").filter((k) => nameWords.has(k.trim()));
need(!dupes.length, `keywords repeat words already in the name or subtitle: ${dupes.join(", ")}`);
for (const s of meta.subtitleAlternatives ?? []) need(s.length <= 30, `subtitle alternative "${s}" is over 30`);

const count = (v, max) => `${[...v].length}/${max}`;
const block = (v) => "```\n" + v + "\n```";
const opts = meta.nameOptions;
const md = `# ${meta.name}: App Store listing

Generated from \`store/metadata.json\` by \`npm run release:config\` (name, version and URLs come from \`app.config.json\`). Edit those, not this file. Copy each block into App Store Connect as is.

## Name

${block(meta.name)}
${count(meta.name, 30)}. Home-screen name under the icon: **${app.displayName}** (\`displayName\` in app.config.json).

Availability, checked ${opts.checkedOn} by searching \`https://itunes.apple.com/search?term=<name>&entity=software\` (US, AU, GB):

| Name | Status | Note |
| --- | --- | --- |
${opts.options.map((o) => `| ${o.name}${o.name === app.storeName ? " (chosen)" : ""} | ${o.status} | ${o.note} |`).join("\n")}

A name someone has reserved in App Store Connect but not shipped won't show up in search; App Store Connect tells you when you create the app record. If it says the name is taken, use the next free option above, put it in \`app.config.json\` as \`storeName\` and run \`npm run release:config\`.

## Subtitle

${block(meta.subtitle)}
${count(meta.subtitle, 30)}. Alternatives: ${(meta.subtitleAlternatives ?? []).map((s) => `"${s}"`).join(", ")}.

## Promotional text

${block(meta.promotionalText)}
${count(meta.promotionalText, 170)}. Can be changed any time without a new build.

## Description

${block(fill(meta.description))}
${count(fill(meta.description), 4000)}.

## Keywords

${block(meta.keywords)}
${count(meta.keywords, 100)}. Comma separated, no spaces after commas, no competitor names, no words already in the name or subtitle (Apple indexes those anyway).

## App information

| Field | Value |
| --- | --- |
| Bundle ID | \`${meta.bundleId}\` |
| SKU | \`${meta.sku}\` |
| Version | ${meta.version} (build ${app.build}) |
| Primary language | ${meta.primaryLanguage} |
| Category | ${meta.category.primary}, subcategories ${meta.category.primarySubcategories.join(" and ")}${meta.category.secondary ? `; secondary ${meta.category.secondary}` : "; no secondary category"} |
| Price | ${meta.price} |
| Copyright | ${meta.copyright} |
| Content rights | ${meta.contentRights} |
| Support URL | ${meta.supportUrl} |
| Privacy Policy URL | ${meta.privacyPolicyUrl} |
| Marketing URL | ${meta.marketingUrl} |
| Export compliance | ${meta.exportCompliance} |
| Release | ${meta.releaseOption} |

## Age rating (expected ${meta.ageRating.expected})

${meta.ageRating._note}

| Question | Answer |
| --- | --- |
${meta.ageRating.answers.map(([q, a]) => `| ${q} | ${a === "None" || a === "No" ? a : `**${a}**`} |`).join("\n")}

${meta.ageRating._why}

## App Privacy

**${meta.appPrivacy.label}.** ${meta.appPrivacy.answer} ${meta.appPrivacy.tracking}

## App Review information

Sign-in required: **${meta.signInRequired ? "Yes" : "No"}** (untick "Sign-in required").

Contact: ${meta.reviewContact.firstName} ${meta.reviewContact.lastName}, ${meta.reviewContact.email}, phone ${meta.reviewContact.phone}.

Notes:

${block(fill(meta.reviewNotes))}

## Screenshots

${meta.screenshots.displaySize} Upload in this order from \`${meta.screenshots.folder}/\`:

${meta.screenshots.order.map((f, i) => `${i + 1}. \`${f}\``).join("\n")}

Re-shoot after art changes: \`npm run dev\` in one terminal, then \`npm run store:shots\`.
`;
write("store/LISTING.md", md);

// ---------------------------------------------------------------- site + checklist: rename in place
const swaps = [
  [old.name, app.storeName],
  [old.email, app.supportEmail],
  [old.site, site],
  [old.copyright, app.copyright],
].filter(([a, b]) => a && b && a !== b);
const docs = [...readdirSync(join(root, "site")).filter((f) => f.endsWith(".html")).map((f) => `site/${f}`), "store/RELEASE-CHECKLIST.md"];
for (const f of docs) {
  if (!existsSync(join(root, f))) continue;
  let s = read(f);
  for (const [a, b] of swaps) s = s.split(a).join(b);
  write(f, s);
}

// ---------------------------------------------------------------- app icon: 1024 square, no alpha (App Store rejects alpha)
const icon = "ios/App/App/Assets.xcassets/AppIcon.appiconset/AppIcon-512@2x.png";
try {
  const out = execFileSync("sips", ["-g", "hasAlpha", "-g", "pixelWidth", "-g", "pixelHeight", join(root, icon)], { encoding: "utf8" });
  need(/hasAlpha: no/.test(out), `${icon} has an alpha channel; App Store rejects it. Re-render with tools/icon.mjs or flatten it`);
  need(/pixelWidth: 1024/.test(out) && /pixelHeight: 1024/.test(out), `${icon} must be 1024x1024`);
} catch (e) {
  if (e.code !== "ENOENT") throw e; // no sips (not a Mac): skip the check
}

if (problems.length) {
  console.error("release-config: fix these before submitting:\n  - " + problems.join("\n  - "));
  process.exit(1);
}
console.log(`release-config: ${app.storeName} (${app.displayName}) ${app.version} (${app.build}) ${app.bundleId} team ${app.teamId}`);
